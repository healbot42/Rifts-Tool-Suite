const source = (pages) => ({ book: 'Rifts Ultimate Edition', pages })

const record = (id, name, category, page, details = {}) => ({
  id: `rue-${id}`,
  name,
  category,
  source: source(String(page)),
  ...details,
})

const feature = (id, name, page, description, cost, location = 'body') =>
  record(id, name, 'features-accessories', page, {
    kind: 'feature',
    location,
    description,
    statistics: [{ label: 'Cost', value: cost }],
  })

const sensor = (id, name, page, description, cost, location = 'head') =>
  record(id, name, 'sensory-optics', page, {
    kind: 'sensor',
    location,
    description,
    statistics: [{ label: 'Cost', value: cost }],
  })

const weapon = (id, name, page, description, statistics, location = 'arm') =>
  record(id, name, 'weapons-tools', page, {
    kind: 'weapon-tool',
    location,
    description,
    statistics,
  })

